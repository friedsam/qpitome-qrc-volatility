"""Run and verify the canonical 63-feature financial QRC simulation.

Two verification scopes are intentionally distinct:

``historical-oracle``
    Reproduce the exact aggregate metric oracle and fold-8 selected readout
    recorded at canonical commit 40ec805c on its original fold lineage.

``current-pipeline``
    Run the same frozen Case151 model and chronological selection procedure on
    folds generated by the current financial-classical pipeline. Verify model
    identity, frozen search grids, test isolation, output completeness, and the
    immutable historical reference hashes. Data-dependent metric and selected
    hyperparameter differences are recorded rather than relabelled as exact
    historical-oracle reproduction.
"""
